#!/bin/bash
set -euo pipefail

# Enhanced logging function
# Also append to a plain file under /var/log, which deployments publish to the
# hypervisor. journald cannot be used for this: its store needs fallocate and
# mmap semantics that a virtiofs mount does not provide, so it silently stays
# volatile and the account of why a cluster came up is lost with the container.
KINC_LOG="${KINC_LOG:-/var/log/kinc/$(basename "$0" .sh).log}"
mkdir -p "$(dirname "$KINC_LOG")" 2>/dev/null || true
log() {
    echo "[$(date -u +%FT%T.%6NZ)] $1" | tee -a "$KINC_LOG" >&2
}

# Start overall timing
POSTINIT_START_TIME=$(date +%s)

log "=== kinc Post-Initialization Starting ==="

# Set kubeconfig for all kubectl commands
export KUBECONFIG=/etc/kubernetes/admin.conf

# Wait for node to register (happens automatically when kubelet starts)
log "Waiting for node to register with API server..."
timeout_counter=0
max_timeout=60
while ! kubectl get nodes 2>/dev/null | grep -q "Ready\|NotReady"; do
    log "Waiting for node registration... (${timeout_counter}s/${max_timeout}s)"
    sleep 2
    timeout_counter=$((timeout_counter + 2))
    if [[ $timeout_counter -ge $max_timeout ]]; then
        log "❌ Node failed to register within ${max_timeout} seconds"
        exit 1
    fi
done
log "✅ Node registered with API server"

# Now complete the kubelet config upload phase that we skipped earlier
log "Completing kubelet configuration upload..."
if kubeadm init phase upload-config kubelet --config=/tmp/kubeadm-final.conf; then
    log "✅ Kubelet configuration uploaded successfully"
else
    log "⚠️  Kubelet config upload failed, but node is registered - continuing..."
fi

# Kubelet configuration is now correctly generated by kubeadm from kubeadm.conf
log "✅ Kubelet configured for rootless operation via kubeadm config"

# Patch kube-proxy to remove privileged flag for rootless operation
log "Patching kube-proxy DaemonSet to remove privileged flag..."
if kubectl patch daemonset kube-proxy -n kube-system --type='json' -p='[{"op": "replace", "path": "/spec/template/spec/containers/0/securityContext/privileged", "value": false}]'; then
    log "✅ kube-proxy patched for rootless operation"
else
    log "❌ Failed to patch kube-proxy for rootless operation"
    exit 1
fi

# Wait for API server to be fully ready before installing any manifests
log "Waiting for API server to be ready..."
timeout_counter=0
max_timeout=60
while ! kubectl get --raw=/healthz >/dev/null 2>&1; do
    log "Waiting for API server to respond... (${timeout_counter}s/${max_timeout}s)"
    sleep 2
    timeout_counter=$((timeout_counter + 2))
    if [[ $timeout_counter -ge $max_timeout ]]; then
        log "❌ API server failed to become ready within ${max_timeout} seconds"
        exit 1
    fi
done

# Additional check: ensure API server can handle requests properly
log "Verifying API server functionality..."
if kubectl get nodes >/dev/null 2>&1; then
    log "✅ API server is ready and responsive"
else
    log "API server not fully ready, waiting additional 5 seconds..."
    sleep 5
    if kubectl get nodes >/dev/null 2>&1; then
        log "✅ API server is now ready and responsive"
    else
        log "❌ API server functionality verification failed"
        exit 1
    fi
fi

# Install the CNI. Antrea is the cluster network: it reads each node's CIDR from
# Node.spec.podCIDR, which kubeadm allocates from podSubnet, so the manifest is
# applied as it ships and a cluster given any podSubnet gets a network that
# agrees with it.
CNI_MANIFEST=/kinc/manifests/antrea-cni.yaml
log "Installing CNI: antrea"
if [[ -f "$CNI_MANIFEST" ]]; then
    # Remove the confs that would otherwise claim pods before Antrea's own is in
    # place: kincnet's, and the bridge conf CRI-O's package installs, which fails
    # pod creation with "keep_addr_on_down ... read-only file system".
    #
    # Antrea's own conf is left alone. It is written by the agent's install-cni
    # init container, which runs only when that pod starts, so deleting it on a
    # restart - when the agent is already running - takes the cluster's network
    # away with nothing to put it back.
    find /etc/cni/net.d -maxdepth 1 -type f \( -name '*.conf' -o -name '*.conflist' \) \
         ! -name '*antrea*' -delete 2>/dev/null || true
    cp "$CNI_MANIFEST" /tmp/cni-manifest.yaml
    if kubectl apply -f /tmp/cni-manifest.yaml; then
        log "✅ CNI installed successfully"
    else
        log "❌ Failed to install CNI"
        exit 1
    fi
else
    log "❌ CNI manifest not found at $CNI_MANIFEST"
    exit 1
fi

# Wait for CNI to be ready before proceeding
# Wait for the DaemonSet, not for pods matching a label.
#
# `kubectl wait --for=condition=Ready pods -l app=antrea` returns an error the
# moment it finds nothing matching, and nothing matches in the instant after the
# manifest is applied - the pods do not exist yet. So it returned in 39
# milliseconds, logged "not ready yet, but continuing", and everything after it
# ran against a cluster with no CNI. It never waited, on any run.
#
# `rollout status` waits for the DaemonSet to become available, which means its
# pods exist, are scheduled and are ready - and since the agent writes
# /etc/cni/net.d/10-antrea.conflist from an init container, an available
# DaemonSet is also the point at which the node can actually give a pod an
# address.
log "Waiting for the CNI DaemonSet to become available..."
wait_start=$(date +%s)
if kubectl rollout status daemonset/antrea-agent -n kube-system --timeout=180s; then
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "✅ CNI pods are ready (waited ${wait_elapsed}s)"
else
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "⚠️  CNI pods not ready yet after ${wait_elapsed}s, but continuing..."
fi

# Wait for nodes to be ready first
log "Waiting for node to be ready..."
wait_start=$(date +%s)
if kubectl wait --for=condition=Ready nodes --all --timeout=240s; then
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "✅ All nodes are ready (waited ${wait_elapsed}s)"
else
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "❌ Nodes failed to become ready after ${wait_elapsed}s"
    exit 1
fi

# Wait for control plane pods to be fully ready and stable
log "Waiting for control plane to be completely stable..."
components=("etcd" "kube-apiserver" "kube-controller-manager" "kube-scheduler")
for component in "${components[@]}"; do
    log "Waiting for $component to be ready..."
    wait_start=$(date +%s)
    if kubectl wait --for=condition=Ready pod -l component="$component" -n kube-system --timeout=180s; then
        wait_end=$(date +%s)
        wait_elapsed=$((wait_end - wait_start))
        log "✅ $component is ready (waited ${wait_elapsed}s)"
    else
        wait_end=$(date +%s)
        wait_elapsed=$((wait_end - wait_start))
        log "❌ $component failed to become ready after ${wait_elapsed}s"
        exit 1
    fi
done

# The four waits above each assert Ready, so the control plane is already
# verified by the time this is reached. What stood here was an unconditional
# five-second sleep labelled as a stability check, which asserted nothing and
# delayed every bootstrap by five seconds - including the storage provisioner,
# which is the phase this chain is measured by.
#
# If a component can report Ready and then not be, that is a condition to assert,
# not a duration to wait out.

# Remove control plane taint so storage provisioner can be scheduled
log "Removing control plane taint to allow workload scheduling..."
if kubectl taint nodes --all node-role.kubernetes.io/control-plane:NoSchedule- 2>/dev/null; then
    log "✅ Control plane taint removed"
else
    log "ℹ️  Control plane taint already removed or not present"
fi

# Now install storage class with fully stable control plane
log "Installing storage class..."
# The static shared volume, alongside the dynamic provisioner rather than
# instead of it.
if [[ -f /kinc/manifests/shared-storage.yaml ]]; then
    # The directory the shared PV points at, created here rather than left to
    # the kubelet.
    #
    # hostPath with DirectoryOrCreate makes it the first time a pod mounts the
    # volume, owned by root and mode 0755 - so a consumer that is not root
    # cannot write to its own subPath, and finds that out at runtime. It is the
    # same shape as the fault that stopped Faro capturing: a directory created
    # by one identity for another to use.
    #
    # 1777, the semantics of a shared scratch area: every consumer can create
    # its subPath, and the sticky bit stops one removing another's. The volume
    # is deliberately shared by components that are not known here and do not
    # share a uid, so a single owner would have to be guessed.
    #
    # The dynamic subtree next door already behaves this way - local-path
    # creates each PV directory 0777 - so both halves of the volume are usable
    # by a non-root pod, which is the point.
    install -d -m 1777 /tmp/kinc-storage/shared
    log "📁 Shared storage directory ready (1777, usable by non-root consumers)"

    log "Installing the shared storage class..."
    if kubectl apply -f /kinc/manifests/shared-storage.yaml; then
        log "✅ Shared storage installed"
    else
        log "❌ Failed to install shared storage"
        exit 1
    fi
fi

if [[ -f /kinc/manifests/default-storage.yaml ]]; then
    if kubectl apply -f /kinc/manifests/default-storage.yaml; then
        log "✅ Storage class installed successfully"
    else
        log "❌ Failed to install storage class"
        exit 1
    fi
else
    log "❌ Storage manifest not found at /kinc/manifests/default-storage.yaml"
    exit 1
fi

# Wait for storage provisioner to be ready
log "Waiting for storage provisioner to be ready..."
wait_start=$(date +%s)
if kubectl wait --for=condition=Available deployment/local-path-provisioner -n local-path-storage --timeout=180s; then
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "✅ Storage provisioner is ready (waited ${wait_elapsed}s)"
else
    wait_end=$(date +%s)
    wait_elapsed=$((wait_end - wait_start))
    log "⚠️  Storage provisioner not ready after ${wait_elapsed}s, but continuing..."
fi

log "=== kinc Post-Initialization Complete ==="

# Calculate and log total post-initialization time
POSTINIT_END_TIME=$(date +%s)
POSTINIT_ELAPSED=$((POSTINIT_END_TIME - POSTINIT_START_TIME))

log "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
log "⏱️  POST-INITIALIZATION TIMING"
log "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
log "   Post-initialization time: ${POSTINIT_ELAPSED}s"
log "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
log "Cluster is ready!"

log "=== Continuing with normal systemd operation ==="

exit 0

